const std = @import("std");
const Io = std.Io;
const json = std.json;

const SpecFile = struct {
    overview: []const u8,
    tests: []const SpecTest,
};

const SpecTest = struct {
    name: []const u8,
    desc: []const u8,
    data: std.json.Value,
    template: []const u8,
    expected: []const u8,
    partials: ?std.json.Value = null,
};

fn writeLiteral(w: *Io.Writer, v: json.Value) !void {
    switch (v) {
        .null => try w.writeAll("null"),
        .bool => |b| try w.writeAll(if (b) "true" else "false"),
        inline .integer, .float => |n| try w.print("{d}", .{n}),
        .number_string => |s| try w.writeAll(s),
        .string => |s| try w.print("\"{f}\"", .{std.zig.fmtString(s)}),
        .array => |a| {
            try w.writeAll(".{ ");
            for (a.items) |item| {
                try writeLiteral(w, item);
                try w.writeAll(", ");
            }
            try w.writeAll("}");
        },
        .object => |o| {
            if (o.count() == 0) return w.writeAll("struct {}{}");
            try w.writeAll(".{ ");
            var oit = o.iterator();
            while (oit.next()) |kv| {
                try w.print(".{f} = ", .{std.zig.fmtId(kv.key_ptr.*)});
                try writeLiteral(w, kv.value_ptr.*);
                try w.writeAll(", ");
            }
            try w.writeAll("}");
        },
    }
}

pub fn main(init: std.process.Init) !void {
    const io = init.io;
    const arena = init.arena.allocator();

    const args = try init.minimal.args.toSlice(arena);
    const spec_path = args[1];
    const out_path = args[2];

    var out: Io.Writer.Allocating = .init(arena);
    const w = &out.writer;

    try w.writeAll(
        \\//generated by tools/gen_spec_tests.zig
        \\const std = @import("std");
        \\const mustache = @import("mustache_zig");
        \\
        \\fn check(comptime template: []const u8, data: anytype, comptime partials: anytype, expected: []const u8) !void {
        \\    const gpa = std.testing.allocator;
        \\    const got = try mustache.allocRender(gpa, template, data, partials);
        \\    defer gpa.free(got);
        \\    try std.testing.expectEqualStrings(expected, got);
        \\}
        \\
        \\
    );

    var dir = try Io.Dir.cwd().openDir(io, spec_path, .{ .iterate = true });
    defer dir.close(io);

    var it = dir.iterate();
    while (try it.next(io)) |entry| {
        if (entry.kind != .file) continue;
        if (!std.mem.endsWith(u8, entry.name, ".json")) continue;

        const bytes = try dir.readFileAlloc(io, entry.name, arena, .limited(1024 * 1024));
        const parsed = try std.json.parseFromSliceLeaky(SpecFile, arena, bytes, .{ .ignore_unknown_fields = true });

        for (parsed.tests, 0..) |t, i| {
            const name = try std.fmt.allocPrint(arena, "{s} #{d}: {s}", .{ entry.name, i, t.name });
            try w.print("test \"{f}\" {{\n", .{std.zig.fmtString(name)});
            try w.writeAll("    const data = ");
            try writeLiteral(w, t.data);
            try w.writeAll(";\n    const partials = ");
            try writeLiteral(w, t.partials orelse .{ .object = .empty });
            try w.print(
                \\;
                \\    try check("{f}", data, partials, "{f}");
                \\}}
                \\
                \\
            , .{ std.zig.fmtString(t.template), std.zig.fmtString(t.expected) });
        }
    }

    try Io.Dir.cwd().writeFile(io, .{ .sub_path = out_path, .data = out.written() });
}
